// Writes shared/crumena-abi.ts from Foundry's build output, so the relayer, the
// scripts and the app all use the exact ABI and bytecode the tests ran against.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const read = (name) => JSON.parse(readFileSync(`${root}contracts/out/${name}.sol/${name}.json`, "utf8"));
const crumena = read("Crumena");
const vault = read("PotVault");

const out = `// Generated by scripts/gen-abi.mjs from contracts/out. Do not edit.
export const CRUMENA_ABI = ${JSON.stringify(crumena.abi, null, 2)} as const;

export const CRUMENA_BYTECODE = "${crumena.bytecode.object}" as const;

export const POT_VAULT_ABI = ${JSON.stringify(vault.abi, null, 2)} as const;
`;
writeFileSync(`${root}shared/crumena-abi.ts`, out);
console.log(`shared/crumena-abi.ts: ${crumena.abi.length} ABI entries, bytecode ${(crumena.bytecode.object.length - 2) / 2} bytes`);
